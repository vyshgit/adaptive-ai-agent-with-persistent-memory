test('UI-only stream: conversation and terminal follow output and resizing without losing manual scrollback across panels', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await page.setViewportSize({ width: 390, height: 844 })
  const { directory } = await localDemo(page)
  await select(page, 'second.ts')
  await view(page, 'Coding')
  const workspaceId = (await api(page, '/builder/status')).data.workspaceId
  const fixture = await outputStreamFixture(page, workspaceId)
  const conversation = page.getByRole('log', { name: 'Project conversation output', exact: true })
  const terminal = page.getByLabel('Native terminal output', { exact: true })
  const atTail = output => output.evaluate(node => node.scrollHeight - node.scrollTop - node.clientHeight < 2)
  const scrollBack = async output => {
    await output.evaluate(node => { node.scrollTop = 0; node.dispatchEvent(new Event('scroll')) })
    await expect.poll(() => output.evaluate(node => node.scrollTop)).toBe(0)
  }
  let answer = Array.from({ length: 80 }, (_, index) => `Visible reply line ${index}: synthetic UI output, not a model result.`).join('\n\n')
  try {
    await coding(page, 'Synthetic output/scroll timing test. No execution is authorized by this fixture.')
    await fixture.started.promise
    fixture.event('delta', { text: answer })
    await expect(conversation).toContainText('Visible reply line 79')
    await expect.poll(() => atTail(conversation)).toBe(true)
    await page.setViewportSize({ width: 320, height: 568 })
    await expect.poll(() => atTail(conversation)).toBe(true)
    await expect(page.getByRole('textbox', { name: 'Coding task', exact: true })).toBeInViewport()
    const heading = page.getByRole('heading', { name: path.basename(directory), exact: true })
    await expect(heading).toBeInViewport()
    expect((await heading.boundingBox()).width).toBeGreaterThan(80)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => atTail(conversation)).toBe(true)
    await scrollBack(conversation)
    answer += '\n\nLATER_REPLY_WHILE_READING_SCROLLBACK'
    fixture.event('delta', { text: '\n\nLATER_REPLY_WHILE_READING_SCROLLBACK' })
    await expect(conversation).toContainText('LATER_REPLY_WHILE_READING_SCROLLBACK')
    await expect.poll(() => conversation.evaluate(node => node.scrollTop)).toBe(0)
    await view(page, 'Memory')
    await expect(conversation).toBeHidden()
    answer += '\n\nREPLY_WHILE_PANEL_HIDDEN'
    fixture.event('delta', { text: '\n\nREPLY_WHILE_PANEL_HIDDEN' })
    await view(page, 'Coding')
    await expect(conversation).toContainText('REPLY_WHILE_PANEL_HIDDEN')
    await expect.poll(() => conversation.evaluate(node => node.scrollTop)).toBe(0)
    await view(page, 'Terminal')
    fixture.event('terminal_started', { command: 'UI-only synthetic command; never executed', cwd: '.', timeoutMs: 1000 })
    fixture.event('terminal_output', { text: Array.from({ length: 100 }, (_, index) => `Synthetic terminal line ${index}\n`).join('') })
    await expect(terminal).toContainText('Synthetic terminal line 99')
    await expect.poll(() => atTail(terminal)).toBe(true)
    await scrollBack(terminal)
    fixture.event('terminal_output', { text: 'LATER_TERMINAL_WHILE_READING_SCROLLBACK\n' })
    await expect(terminal).toContainText('LATER_TERMINAL_WHILE_READING_SCROLLBACK')
    await expect.poll(() => terminal.evaluate(node => node.scrollTop)).toBe(0)
    await view(page, 'Memory')
    fixture.event('terminal_output', { text: 'TERMINAL_WHILE_PANEL_HIDDEN\n' })
    await view(page, 'Terminal')
    await expect(terminal).toContainText('TERMINAL_WHILE_PANEL_HIDDEN')
    await expect.poll(() => terminal.evaluate(node => node.scrollTop)).toBe(0)
    fixture.event('terminal_done', { status: 'exited', exitCode: 0 })
    fixture.event('terminal_started', { command: 'A new UI-only synthetic command; never executed', cwd: '.', timeoutMs: 1000 })
    fixture.event('terminal_output', { text: Array.from({ length: 100 }, (_, index) => `New synthetic terminal line ${index}\n`).join('') })
    await expect(terminal).toContainText('New synthetic terminal line 99')
    await expect.poll(() => atTail(terminal)).toBe(true)
    await page.setViewportSize({ width: 1440, height: 1000 })
    await expect.poll(() => atTail(terminal)).toBe(true)
    await expect(conversation).toBeVisible()
    await expect.poll(() => conversation.evaluate(node => node.scrollTop)).toBe(0)
    fixture.event('terminal_done', { status: 'exited', exitCode: 0 })
    fixture.finish(answer)
    await expect(page.getByRole('button', { name: 'New project session', exact: true })).toBeEnabled()
    expect((await api(page, '/memory')).data.inventory.total).toBe(0)
    checkErrors()
  } finally { await fixture.close() }
})

test('a failed connection-status refresh preserves local drafts and model selection but blocks new model tasks until status recovers', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await localDemo(page)
  const editor = await select(page, 'second.ts')
  await editor.fill('// PRIVATE_DRAFT_SURVIVES_STATUS_FAILURE\n')
  await view(page, 'Coding')
  const task = page.getByRole('textbox', { name: 'Coding task', exact: true })
  await task.fill('PRIVATE_TASK_SURVIVES_STATUS_FAILURE')
  await page.route('**/api/agent/status', route => route.fulfill({ status: 503, json: { code: 'synthetic_status_failure', error: 'Synthetic status request failed.', retryable: true } }))
  const settings = await openSettings(page, 'Advanced')
  await settings.getByLabel('Workspace bearer token', { exact: true }).fill('SYNTHETIC_LOCAL_STATUS_TOKEN')
  await settings.getByRole('button', { name: 'Unlock this tab', exact: true }).click()
  await expect(settings.getByRole('alert')).toContainText('Could not refresh workspace access')
  await settings.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(task).toHaveValue('PRIVATE_TASK_SURVIVES_STATUS_FAILURE')
  await expect(page.getByRole('combobox', { name: 'Project model', exact: true })).toHaveValue('recallloop-mock')
  await expect(page.getByRole('button', { name: 'Send coding task', exact: true })).toBeDisabled()
  await view(page, 'Files')
  await expect(editor).toHaveValue('// PRIVATE_DRAFT_SURVIVES_STATUS_FAILURE\n')
  await page.unroute('**/api/agent/status')
  await page.getByRole('button', { name: 'Retry status', exact: true }).click()
  await view(page, 'Coding')
  await expect(task).toHaveValue('PRIVATE_TASK_SURVIVES_STATUS_FAILURE')
  await expect(page.getByRole('button', { name: 'Send coding task', exact: true })).toBeEnabled()
  checkErrors()
})

test('UI-only capture stream: completed tasks stay complete through delayed, pending and interrupted memory confirmation', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await localDemo(page)
  const workspaceId = (await api(page, '/builder/status')).data.workspaceId
  const tasks = page.getByRole('region', { name: 'Local coding tasks', exact: true })
  for (const outcome of ['confirmed', 'pending', 'interrupted']) {
    const fixture = await outputStreamFixture(page, workspaceId)
    try {
      await coding(page, `Synthetic ${outcome} memory confirmation; no real provider or storage operation.`)
      await fixture.started.promise
      fixture.event('done', { answer: 'Completed synthetic coding reply.', requests: 1 })
      await expect(tasks.getByText('Task completed · not a test verdict', { exact: true })).toHaveCount(1)
      const status = tasks.getByRole('status', { name: 'Memory capture status', exact: true })
      await expect(status).toContainText('Remembering relevant context')
      if (outcome === 'interrupted') fixture.disconnect()
      else {
        fixture.event('stored', { verbatim: 0, facts: outcome === 'confirmed' ? 1 : 0, failed: 0, blobs: [],
          ...(outcome === 'pending' ? { pending: true, message: 'Synthetic capture pending; check inventory.' } : {}) })
        fixture.end()
      }
      await expect(page.getByRole('button', { name: 'Stop active task', exact: true })).toBeHidden()
      await expect(status).toContainText(outcome === 'confirmed' ? '0 transcript records · 1 facts confirmed'
        : outcome === 'pending' ? 'Synthetic capture pending' : 'Memory confirmation was interrupted')
      await expect(tasks.getByText('Task completed · not a test verdict', { exact: true })).toHaveCount(1)
      await expect(tasks).not.toContainText('Task stopped')
      await expect(tasks).not.toContainText('Task failed')
      await page.getByRole('button', { name: 'New project session', exact: true }).click()
    } finally { await fixture.close() }
  }
  expect((await api(page, '/memory')).data.inventory.total).toBe(0)
  checkErrors()
})
