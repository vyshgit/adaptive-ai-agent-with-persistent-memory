async function captureWorkspace(page, testInfo, name) {
  await expect(page.locator('html')).toHaveAttribute('data-theme', name.endsWith('-dark.png') ? 'dark' : 'light')
  // A theme toggle transitions the controls after the canvas changes. Capture
  // the settled token colors, not an intermediate light/dark combination.
  // Mobile Terminal hides the conversation, including its model picker.
  const control = name.startsWith('integrated-terminal-') ? page.getByRole('textbox', { name: 'Native command', exact: true })
    : page.getByRole('combobox', { name: 'Project model', exact: true })
  await expect(control).toBeVisible()
  await expect.poll(() => control.evaluate(node =>
    getComputedStyle(node).backgroundColor === getComputedStyle(document.body).backgroundColor)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath(name), animations: 'disabled' })
}

test('standard permissions save routine editor changes and inspect the launch folder automatically, while scripts and execution configuration still ask', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  const { directory } = await localDemo(page)
  const review = page.getByRole('dialog', { name: 'Review disk change', exact: true })
  await newFileDraft(page, 'automatic-save.ts')
  const editor = page.getByRole('textbox', { name: 'Local file editor', exact: true })
  await editor.fill('export const automatic = 1\n')
  await page.getByRole('button', { name: 'Save to disk', exact: true }).click()
  await expect.poll(() => readFile(path.join(directory, 'automatic-save.ts'), 'utf8')).toBe('export const automatic = 1\n')
  await expect(review).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Save to disk', exact: true })).toBeDisabled()
  const delayed = await holdFileResponse(page, 'automatic-save.ts')
  try {
    await editor.fill('export const automatic = 2\n')
    await page.getByRole('button', { name: 'Save to disk', exact: true }).click()
    await delayed.started.promise
    await editor.fill('// NEWER_DRAFT_AFTER_AUTOMATIC_SAVE\n')
    delayed.release.resolve(); await delayed.finished.promise
    await expect(editor).toHaveValue('// NEWER_DRAFT_AFTER_AUTOMATIC_SAVE\n')
    expect(await readFile(path.join(directory, 'automatic-save.ts'), 'utf8')).toBe('export const automatic = 2\n')
  } finally { delayed.release.resolve() }
  await view(page, 'Terminal')
  await page.getByRole('textbox', { name: 'Native command', exact: true }).fill('pwd')
  await page.getByRole('button', { name: 'Run command', exact: true }).click()
  await expect(page.getByLabel('Native terminal output', { exact: true })).toContainText(directory, { timeout: 30_000 })
  await expect(page.getByRole('region', { name: 'Local native terminal', exact: true })).toContainText('Exited with code 0.')
  await expect(page.getByRole('dialog', { name: 'Review native command', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Run command', exact: true })).toBeEnabled()
  await page.getByRole('textbox', { name: 'Native command', exact: true }).fill('npm test')
  await page.getByRole('button', { name: 'Run command', exact: true }).click()
  const command = page.getByRole('dialog', { name: 'Review native command', exact: true })
  await expect(command).toContainText('Why permission is needed')
  await expect(command).toContainText('project scripts')
  await command.getByRole('button', { name: 'Reject action', exact: true }).click()
  await expect(command).toBeHidden()
  // Discard only this test's unsaved editor text before creating a config draft.
  await view(page, 'Files')
  await editor.fill('export const automatic = 2\n')
  await newFileDraft(page, 'package.json')
  await editor.fill('{"scripts":{"test":"node test.mjs"}}\n')
  await page.getByRole('button', { name: 'Save to disk', exact: true }).click()
  await expect(review).toContainText('project execution, dependencies or automation configuration')
  const ticket = (await api(page, '/builder/status')).data.approvals[0]
  await review.getByRole('button', { name: 'Close dialog', exact: true }).click()
  const permissions = await projectPermissions(page)
  await permissions.getByRole('combobox', { name: 'Project permissions', exact: true }).selectOption('strict')
  await expect(permissions.getByRole('combobox', { name: 'Project permissions', exact: true })).toHaveValue('strict')
  await expect(page.getByRole('region', { name: 'Pending local approvals', exact: true })).toHaveCount(0)
  expect((await api(page, '/builder/approvals', { workspaceId: ticket.workspaceId, id: ticket.id, digest: ticket.digest, decision: 'approve' })).status).toBe(409)
  await permissions.locator('summary').click()
  await page.getByRole('button', { name: 'Save to disk', exact: true }).click()
  await expect(review).toContainText('Strict review is enabled')
  await review.getByRole('button', { name: 'Reject action', exact: true }).click()
  await expect(review).toBeHidden()
  expect(await stat(path.join(directory, 'package.json')).then(() => true, () => false)).toBe(false)
  expect((await api(page, '/memory')).data.inventory.total).toBe(0)
  checkErrors()
})

