import { test, expect } from './harness.mjs'
import { api, localDemo, localWallet, select, view, closeFolder, openFolder } from './helpers.mjs'
import { cachedValues, failOnPageErrors, installWallet, openSettings } from '../helpers.mjs'
import { installConnectionFixture, syntheticConnection } from '../fixtures.mjs'
import { PREFERENCES_KEY } from '../../src/agent/workspacePreferences.ts'

test.use({ signInBudget: 1 })
const taskOptions = page => page.getByRole('region', { name: 'Local coding tasks', exact: true }).locator('details').filter({ has: page.getByText(/^Task options/) })

test('workspace variables reload without caching local work, command text or Walrus/project consent, and never execute themselves', async ({ page }) => {
  const checkErrors = failOnPageErrors(page), mutations = []
  page.on('request', request => { if (request.method() === 'POST' && /\/api\/agent\/builder\//.test(request.url())) mutations.push(new URL(request.url()).pathname) })
  await localDemo(page)
  const editor = await select(page, 'second.ts')
  await editor.fill('// PRIVATE_NATIVE_EDITOR_NOT_CACHED\n')
  await view(page, 'Coding')
  await page.getByRole('combobox', { name: 'Agent mode', exact: true }).selectOption('plan')
  await page.getByRole('textbox', { name: 'Coding task', exact: true }).fill('PRIVATE_NATIVE_TASK_NOT_CACHED')
  await expect(page.getByRole('checkbox', { name: 'Auto-memory', exact: true })).toBeChecked()
  await page.getByRole('checkbox', { name: 'Auto-memory', exact: true }).uncheck()
  await taskOptions(page).locator('summary').click()
  await page.getByRole('checkbox', { name: 'Auto-recall', exact: true }).check()
  await taskOptions(page).locator('summary').click()
  await view(page, 'Terminal')
  await page.getByRole('textbox', { name: 'Native command', exact: true }).fill('PRIVATE_NATIVE_COMMAND_NOT_CACHED')
  await page.getByRole('region', { name: 'Local native terminal', exact: true }).locator('summary').click()
  await page.getByRole('textbox', { name: 'Relative working directory', exact: true }).fill('dist')
  await page.getByRole('spinbutton', { name: 'Timeout (seconds)', exact: true }).fill('45')
  await view(page, 'Preview')
  await page.getByRole('textbox', { name: 'Static output folder', exact: true }).fill('site-output')
  await page.getByRole('textbox', { name: 'HTML entry', exact: true }).fill('home.html')
  await view(page, 'Coding')
  await page.getByRole('button', { name: 'Hide project explorer', exact: true }).click()
  const cached = await cachedValues(page)
  const config = JSON.parse(cached.find(([key]) => key.startsWith(`sessionStorage:${PREFERENCES_KEY}:`))[1]).preferences
  expect(config.builder).toMatchObject({ explorer: false, mode: 'plan', cwd: 'dist', seconds: 45, outputFolder: 'site-output', entry: 'home.html' })
  expect(config.autoMemory).toBe(false)
  expect(JSON.stringify(cached)).not.toMatch(/PRIVATE_NATIVE_|folderConsent|useMemory|approval|command|draft/)
  expect(cached.some(([key]) => /^sessionStorage:recallloop\.(sessions|project)\./.test(key))).toBe(false)
  mutations.length = 0
  page.once('dialog', dialog => dialog.accept())
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Agent mode', exact: true })).toHaveValue('plan')
  await expect(page.getByRole('textbox', { name: 'Coding task', exact: true })).toHaveValue('')
  await expect(page.getByRole('checkbox', { name: 'Auto-memory', exact: true })).not.toBeChecked()
  await expect(page.getByRole('button', { name: 'Show project explorer', exact: true })).toBeVisible()
  await taskOptions(page).locator('summary').click()
  await expect(page.getByRole('checkbox', { name: 'Auto-recall', exact: true })).not.toBeChecked()
  await taskOptions(page).locator('summary').click()
  await view(page, 'Terminal')
  await expect(page.getByRole('textbox', { name: 'Native command', exact: true })).toHaveValue('')
  await expect(page.getByLabel('Native terminal output', { exact: true })).toContainText('Command output appears here')
  await page.getByRole('region', { name: 'Local native terminal', exact: true }).locator('summary').click()
  await expect(page.getByRole('textbox', { name: 'Relative working directory', exact: true })).toHaveValue('dist')
  await expect(page.getByRole('spinbutton', { name: 'Timeout (seconds)', exact: true })).toHaveValue('45')
  await view(page, 'Preview')
  await expect(page.getByRole('textbox', { name: 'Static output folder', exact: true })).toHaveValue('site-output')
  await expect(page.getByRole('textbox', { name: 'HTML entry', exact: true })).toHaveValue('home.html')
  await expect(page.getByRole('button', { name: 'Create static preview', exact: true })).toBeEnabled()
  expect(mutations).toEqual([])
  expect((await api(page, '/builder/status')).data).toMatchObject({ permissionMode: 'standard', task: null, approvals: [] })
  await closeFolder(page)
  await expect(page.getByRole('checkbox', { name: 'I trust this project and consent to its selected permissions for this login.', exact: true })).not.toBeChecked()
  await expect(page.getByRole('button', { name: 'Open project', exact: true })).toBeDisabled()
  await openFolder(page)
  await expect(page.getByRole('combobox', { name: 'Agent mode', exact: true })).toHaveValue('plan')
  checkErrors()
})

test('a cached project model stays catalogue-bound across reload and provider changes without starting an SDK task', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await localDemo(page)
  const fixture = await installConnectionFixture(page, { connection: syntheticConnection() })
  await page.reload()
  await page.getByRole('combobox', { name: 'Project model', exact: true }).selectOption('synthetic-provider|synthetic-discovered-only')
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Project model', exact: true })).toHaveValue('synthetic-provider|synthetic-discovered-only')
  fixture.setConnections([syntheticConnection({ baseUrl: 'https://api.openai.com/v1' })])
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Project model', exact: true })).toHaveValue('synthetic-provider|synthetic-exact-model')
  expect(fixture.mutations()).toEqual([])
  expect((await api(page, '/builder/status')).data.task).toBeNull()
  checkErrors()
})

test('UI-only local catalogue: signed-in startup discovers key-free models, preserves provider choice, and refresh handles removals without starting tasks', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await installWallet(page)
  const initialDiscovery = page.waitForResponse('**/api/agent/models/local')
  await localWallet(page)
  await initialDiscovery
  const remote = syntheticConnection({ model: 'shared-model' })
  const local = syntheticConnection({ id: 'local-ollama', name: 'Ollama local', baseUrl: 'http://127.0.0.1:11434/v1',
    apiStyle: 'chat', model: 'shared-model', models: [{ id: 'shared-model', label: 'shared-model', cost: 'local' }],
    source: 'local-discovery', verified: false, verification: null })
  const fixture = await installConnectionFixture(page, { connection: remote, localConnection: local })
  await page.reload()
  const picker = page.getByRole('combobox', { name: 'Project model', exact: true })
  await expect(picker.locator('optgroup')).toHaveCount(2)
  await expect(picker).toHaveValue('synthetic-provider|shared-model')
  await expect(picker.locator('option[value="local-ollama|shared-model"]')).toHaveText('Ollama local · shared-model · Local · no API key')
  expect(fixture.mutations().map(request => [request.path, request.body])).toEqual([['/models/local', {}]])
  await picker.selectOption('local-ollama|shared-model')
  await page.reload()
  await expect(picker).toHaveValue('local-ollama|shared-model')
  await expect(picker).toBeEnabled()
  const settings = await openSettings(page)
  await expect(settings).toContainText('1 installed local models available without an API key.')
  await settings.getByRole('button', { name: 'Done', exact: true }).click()
  const beforeFocus = fixture.mutations().length
  const refreshed = page.waitForResponse('**/api/agent/status')
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await refreshed
  await expect(picker).toHaveValue('local-ollama|shared-model')
  expect(fixture.mutations()).toHaveLength(beforeFocus)
  await openSettings(page)
  fixture.state.localConnection = null
  await settings.getByRole('button', { name: 'Refresh local models', exact: true }).click()
  await expect(settings).toContainText('No installed local Ollama models found.')
  await expect(settings.getByRole('button', { name: 'Refresh local models', exact: true })).toBeEnabled()
  await settings.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(picker).toHaveValue('synthetic-provider|shared-model')
  await expect(picker.locator('optgroup')).toHaveCount(1)
  expect(fixture.state.modelConnections.map(profile => profile.id)).toEqual(['synthetic-provider'])
  expect(fixture.mutations().map(request => [request.path, request.body])).toEqual(Array.from({ length: 3 }, () => ['/models/local', {}]))
  expect((await api(page, '/builder/status')).data).toMatchObject({ task: null, approvals: [] })
  checkErrors()
})
