test('delayed selections and post-approval reads cannot replace a later selected file or a newer unsaved draft', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  const { directory } = await localDemo(page, { permissionMode: 'strict' })
  await writeFile(path.join(directory, 'first.ts'), 'export const first = 1\n')
  const first = await holdFileResponse(page, 'first.ts')
  try {
    await page.getByRole('complementary', { name: 'Local project files', exact: true }).getByRole('button', { name: 'first.ts', exact: true }).click()
    await first.started.promise
    const editor = await select(page, 'second.ts')
    await expect(editor).toHaveValue('export const second = 2\n')
    first.release.resolve(); await first.finished.promise
    await expect(editor).toHaveValue('export const second = 2\n')
    await select(page, 'first.ts')
    await editor.fill('export const first = 3\n')
    await page.getByRole('button', { name: 'Save to disk', exact: true }).click()
    const applied = await holdFileResponse(page, 'first.ts')
    try {
      const review = page.getByRole('dialog', { name: 'Review disk change', exact: true })
      await review.getByRole('button', { name: 'Apply reviewed disk edit', exact: true }).click()
      await applied.started.promise
      await expect(review).toBeHidden()
      await editor.fill('// LATE_TRANSPORT_DRAFT\n')
      applied.release.resolve(); await applied.finished.promise
      await expect(editor).toHaveValue('// LATE_TRANSPORT_DRAFT\n')
      expect(await readFile(path.join(directory, 'first.ts'), 'utf8')).toBe('export const first = 3\n')
    } finally { applied.release.resolve() }
    checkErrors()
  } finally { first.release.resolve() }
})

