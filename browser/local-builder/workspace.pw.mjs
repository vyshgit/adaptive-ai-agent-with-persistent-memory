test('the real launcher defaults to local folder consent; reviewed saves, empty-file creation and deletion are real and once-only', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  const { builder, directory } = await localDemo(page, { open: false })
  await expect(builder).toContainText('Auto-memory')
  expect((await api(page, '/builder/status')).data.opened).toBe(false)
  await openFolder(page, 'strict')
  await expect(page.getByRole('complementary', { name: 'Local project files', exact: true })).not.toContainText('.env')
  const editor = await select(page, 'first.ts')
  await editor.fill('export const first = 42 // PRIVATE_LOCAL_SOURCE\n')
  expect(await readFile(path.join(directory, 'first.ts'), 'utf8')).toBe('export const first = 1\n')
  await page.getByRole('button', { name: 'Save to disk', exact: true }).click()
  const review = page.getByRole('dialog', { name: 'Review disk change', exact: true })
  await expect(review).toContainText('PRIVATE_LOCAL_SOURCE')
  await review.getByRole('tab', { name: 'Before', exact: true }).click()
  await expect(review.getByRole('tabpanel')).toContainText('export const first = 1')
  await review.getByRole('tab', { name: 'After', exact: true }).click()
  await expect(review.getByRole('tabpanel')).toContainText('PRIVATE_LOCAL_SOURCE')
  await review.getByRole('button', { name: 'Apply reviewed disk edit', exact: true }).click()
  await expect(review).toBeHidden()
  await expect(editor).toHaveValue('export const first = 42 // PRIVATE_LOCAL_SOURCE\n')
  await expect.poll(() => readFile(path.join(directory, 'first.ts'), 'utf8')).toContain('PRIVATE_LOCAL_SOURCE')
  await expect(page.getByRole('button', { name: 'Save to disk', exact: true })).toBeDisabled()
  await newFileDraft(page, 'empty.txt')
  await page.getByRole('button', { name: 'Save to disk', exact: true }).click()
  await review.getByRole('button', { name: 'Apply reviewed disk edit', exact: true }).click()
  await expect(review).toBeHidden()
  await expect.poll(() => readFile(path.join(directory, 'empty.txt'), 'utf8')).toBe('')
  await expect(page.getByRole('button', { name: 'Review file deletion', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Review file deletion', exact: true }).click()
  await expect(review).toContainText('delete:')
  await review.getByRole('button', { name: 'Apply reviewed disk edit', exact: true }).click()
  await expect(review).toBeHidden()
  await expect.poll(() => stat(path.join(directory, 'empty.txt')).then(() => true, () => false)).toBe(false)
  expect((await api(page, '/builder/status')).data.approvals).toEqual([])
  expect((await api(page, '/memory')).data.inventory.total).toBe(0)
  expect(JSON.stringify(await cachedValues(page))).not.toContain('PRIVATE_LOCAL_SOURCE')
  checkErrors()
})

