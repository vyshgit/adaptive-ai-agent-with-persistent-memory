test('a reviewed deletion keeps a later page draft without recreating the file or reusing its disk authority', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  const { directory } = await localDemo(page, { permissionMode: 'strict' })
  const filename = 'draft-delete.ts', absolute = path.join(directory, filename), original = 'export const keep = 1\n'
  await writeFile(absolute, original)
  await page.getByRole('button', { name: 'Refresh local files', exact: true }).click()
  const editor = await select(page, filename)
  await page.getByRole('button', { name: 'Review file deletion', exact: true }).click()
  const review = page.getByRole('dialog', { name: 'Review disk change', exact: true })
  await expect(review).toContainText(`delete: ${filename}`)
  const { workspaceId, approvals: [deletion] } = (await api(page, '/builder/status')).data
  await review.getByRole('button', { name: 'Close dialog', exact: true }).click()
  await editor.fill('// LATER_DELETION_PRIVATE_DRAFT\n')
  expect(await readFile(absolute, 'utf8')).toBe(original)
  await page.getByRole('region', { name: 'Pending local approvals', exact: true }).getByRole('button', { name: `Review ${filename}`, exact: true }).click()
  await review.getByRole('button', { name: 'Apply reviewed disk edit', exact: true }).click()
  await expect(review).toBeHidden()
  await expect.poll(() => stat(absolute).then(() => true, () => false)).toBe(false)
  await expect(editor).toHaveValue('// LATER_DELETION_PRIVATE_DRAFT\n')
  await expect(page.getByRole('button', { name: 'Review file deletion', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Save to disk', exact: true })).toBeEnabled()
  await expect(page.getByRole('region', { name: 'Local builder workspace', exact: true })).toContainText('Your later unsaved editor draft was kept')
  const replay = await api(page, '/builder/approvals', { workspaceId, id: deletion.id, digest: deletion.digest, decision: 'approve' })
  expect(replay.status).toBe(409)
  expect(replay.data.code).toBe('approval_invalid')
  await page.getByRole('button', { name: 'Save to disk', exact: true }).click()
  await expect(review).toContainText(`create: ${filename}`)
  expect(await stat(absolute).then(() => true, () => false)).toBe(false)
  await review.getByRole('button', { name: 'Apply reviewed disk edit', exact: true }).click()
  await expect(review).toBeHidden()
  await expect.poll(() => readFile(absolute, 'utf8')).toBe('// LATER_DELETION_PRIVATE_DRAFT\n')
  expect((await api(page, '/memory')).data.inventory.total).toBe(0)
  expect(JSON.stringify(await cachedValues(page))).not.toContain('LATER_DELETION_PRIVATE_DRAFT')
  checkErrors()
})

test('UI-only streaming fixture: an old approval acknowledgement cannot dismiss a newer dialog while its parent task runs', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await localDemo(page)
  const workspaceId = (await api(page, '/builder/status')).data.workspaceId
  const fixture = await approvalStreamFixture(page, workspaceId)
  try {
    await coding(page, 'Synthetic approval-dialog race; no real execution.')
    await fixture.started.promise
    const review = page.getByRole('dialog', { name: 'Review disk change', exact: true })
    await expect(review).toContainText('first.ts')
    await review.getByRole('button', { name: 'Apply reviewed disk edit', exact: true }).click()
    await expect(review).toContainText('second.ts')
    await expect(review.getByRole('button', { name: 'Apply reviewed disk edit', exact: true })).toBeDisabled()
    fixture.ack.resolve()
    await expect(review.getByRole('button', { name: 'Apply reviewed disk edit', exact: true })).toBeEnabled()
    await expect(review).toContainText('second.ts')
    await review.getByRole('button', { name: 'Reject action', exact: true }).click()
    await expect(review).toBeHidden()
    await expect(page.getByRole('button', { name: 'Stop active task', exact: true })).toBeHidden()
    expect(fixture.decisions.map(entry => [entry.id, entry.decision])).toEqual([['1', 'approve'], ['2', 'reject']])
    checkErrors()
  } finally { await fixture.close() }
})

