test('reviewed checkpoints and selected recall work independently with Auto-memory disabled', async ({ page }) => {
  const checkErrors = failOnPageErrors(page), requests = []
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/agent/builder/prompt') requests.push(request.postDataJSON()) })
  await localDemo(page)
  await page.getByRole('checkbox', { name: 'Auto-memory', exact: true }).uncheck()
  await page.getByRole('checkbox', { name: 'Auto-recall', exact: true }).uncheck()
  await view(page, 'Memory')
  await expect(page.getByRole('checkbox', { name: 'Also retrieve raw chat (separate consent)', exact: true })).not.toBeChecked()
  await page.getByRole('button', { name: 'New checkpoint', exact: true }).click()
  await page.getByRole('textbox', { name: 'Reviewed preferences', exact: true }).fill('I prefer TypeScript and npm. REVIEWED_CHECKPOINT_ONLY')
  await page.getByRole('textbox', { name: 'Reviewed decisions / outcome', exact: true }).fill('Use local execution with once-only approvals.')
  await page.getByRole('button', { name: 'Review checkpoint text', exact: true }).click()
  const review = page.getByRole('dialog', { name: 'Review Walrus checkpoint', exact: true })
  await expect(review).toContainText('REVIEWED_CHECKPOINT_ONLY')
  await expect(review).toContainText('not a Mainnet write')
  expect((await api(page, '/memory')).data.inventory.total).toBe(0)
  await expect(review.getByRole('button', { name: 'Save reviewed checkpoint', exact: true })).toBeDisabled()
  await review.getByRole('checkbox', { name: 'I reviewed this checkpoint and consent to saving this exact text.', exact: true }).check()
  await review.getByRole('button', { name: 'Save reviewed checkpoint', exact: true }).click()
  await expect(review).toBeHidden()
  await expect(page.getByRole('region', { name: 'Local builder workspace', exact: true })).toContainText('Checkpoint write confirmed · mock-')
  const inventory = (await api(page, '/memory')).data.inventory
  expect(inventory.total).toBe(1)
  expect(inventory.namespaces.find(entry => entry.name.endsWith(':raw')).count).toBe(0)
  await page.getByRole('textbox', { name: 'Memory query', exact: true }).fill('TypeScript npm local execution')
  await page.getByRole('button', { name: 'Recall and review', exact: true }).click()
  const attach = page.getByRole('checkbox', { name: 'Attach reviewed memory 1 · facts', exact: true })
  await expect(attach).not.toBeChecked()
  await coding(page, 'No memory attachment is authorized for this task.')
  await expect(page.getByRole('button', { name: 'Stop local task', exact: true })).toBeHidden({ timeout: 30_000 })
  expect(requests.at(-1)).not.toHaveProperty('memoryIds')
  await view(page, 'Memory')
  await attach.check()
  await coding(page, 'Use only the explicitly selected reviewed context.')
  await expect(page.getByRole('button', { name: 'Stop local task', exact: true })).toBeHidden({ timeout: 30_000 })
  expect(requests.at(-1).memoryIds).toEqual([inventory.memories[0].blobId])
  expect(requests.at(-1).recallId).toBeTruthy()
  expect(requests.at(-1)).toMatchObject({ capture: false, useMemory: false })
  expect((await api(page, '/memory')).data.inventory.total).toBe(1)
  await view(page, 'Memory')
  await page.getByRole('button', { name: 'Clear recalled context', exact: true }).click()
  await expect(attach).toHaveCount(0)
  expect(JSON.stringify(await cachedValues(page))).not.toContain('REVIEWED_CHECKPOINT_ONLY')
  checkErrors()
})

test('an expired reviewed recall stays visibly selected but cannot send an attachment or silently start an ungrounded task', async ({ page }) => {
  const checkErrors = failOnPageErrors(page), requests = []
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/agent/builder/prompt') requests.push(request.postDataJSON()) })
  await page.clock.install()
  await localDemo(page)
  await saveCheckpoint(page, 'I prefer TypeScript. EXPIRING_REVIEWED_CONTEXT')
  await page.getByRole('textbox', { name: 'Memory query', exact: true }).fill('TypeScript')
  const result = page.waitForResponse(response => new URL(response.url()).pathname === '/api/agent/builder/recall')
  await page.getByRole('button', { name: 'Recall and review', exact: true }).click()
  const recall = await (await result).json()
  const attach = page.getByRole('checkbox', { name: 'Attach reviewed memory 1 · facts', exact: true })
  await attach.check()
  await page.clock.fastForward(Math.max(0, recall.expiresAt - await page.evaluate(() => Date.now())) + 1)
  await expect(attach).toBeChecked()
  await expect(attach).toBeDisabled()
  await expect(page.getByRole('region', { name: 'Reviewed memory recall', exact: true })).toContainText('Recall expired')
  await coding(page, 'This task must not silently discard my expired attachment.')
  await expect(page.getByRole('region', { name: 'Local builder workspace', exact: true }).getByRole('alert')).toContainText('The selected recall expired')
  await expect(page.getByRole('textbox', { name: 'Coding task', exact: true })).toHaveValue('This task must not silently discard my expired attachment.')
  expect(requests).toEqual([])
  await expect(page.getByRole('region', { name: 'Local coding tasks', exact: true })).not.toContainText('Task completed')
  await view(page, 'Memory')
  await page.getByRole('button', { name: 'Clear recalled context', exact: true }).click()
  await expect(attach).toHaveCount(0)
  await coding(page, 'I explicitly cleared that context; run a fresh offline task.')
  await expect(page.getByRole('button', { name: 'Stop local task', exact: true })).toBeHidden({ timeout: 30_000 })
  expect(requests).toHaveLength(1)
  expect(requests[0]).not.toHaveProperty('memoryIds')
  expect(requests[0]).not.toHaveProperty('recallId')
  checkErrors()
})

test('a real mock-memory replacement revokes recall and checkpoint approvals even when the public memory binding is unchanged', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await localDemo(page)
  await saveCheckpoint(page, 'I prefer TypeScript. REVOKED_MOCK_CONTEXT')
  await page.getByRole('textbox', { name: 'Memory query', exact: true }).fill('TypeScript')
  await page.getByRole('button', { name: 'Recall and review', exact: true }).click()
  const attach = page.getByRole('checkbox', { name: 'Attach reviewed memory 1 · facts', exact: true })
  await attach.check()
  await page.getByRole('textbox', { name: 'Reviewed decisions / outcome', exact: true }).fill('This checkpoint must be revoked.')
  await page.getByRole('button', { name: 'Review checkpoint text', exact: true }).click()
  const review = page.getByRole('dialog', { name: 'Review Walrus checkpoint', exact: true })
  await expect(review).toBeVisible()
  const before = (await api(page, '/builder/status')).data, approval = before.approvals[0]
  const publicBefore = (await api(page, '/status')).data
  await review.getByRole('button', { name: 'Close dialog', exact: true }).click()
  expect((await api(page, '/connections/memwal/disconnect', {})).status).toBe(200)
  const publicAfter = (await api(page, '/status')).data
  expect(publicAfter.memory.mode).toBe(publicBefore.memory.mode)
  expect(publicAfter.memoryConnection).toEqual(publicBefore.memoryConnection)
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await expect(attach).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Pending local approvals', exact: true })).toHaveCount(0)
  const after = (await api(page, '/builder/status')).data
  expect(after.memoryEpoch).toBe(before.memoryEpoch + 1)
  const replay = await api(page, '/builder/approvals', { workspaceId: before.workspaceId, id: approval.id, digest: approval.digest, decision: 'approve' })
  expect(replay.status).toBe(409)
  expect(replay.data.code).toBe('approval_invalid')
  expect((await api(page, '/memory')).data.inventory.total).toBe(0)
  checkErrors()
})

test('UI-only connection fixtures: reconnecting the same wallet memory account removes prior reviewed recall and checkpoint controls', async ({ page }) => {
  const checkErrors = failOnPageErrors(page), requests = []
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/agent/builder/prompt') requests.push(request.postDataJSON()) })
  await installWallet(page)
  await localWallet(page)
  const connection = (await api(page, '/connect', { mode: 'mock' })).data.connection
  const fixture = await installConnectionFixture(page, { connection, tatum: true, memory: true })
  const workspaceId = (await api(page, '/builder/status')).data.workspaceId
  let checkpoint
  await page.route('**/api/agent/builder/status', async route => {
    const response = await route.fetch(), status = await response.json()
    await route.fulfill({ response, json: { ...status, memoryEpoch: fixture.state.memoryEpoch,
      approvals: checkpoint && fixture.state.memoryEpoch === 0 ? [checkpoint] : [] } })
  })
  await page.route('**/api/agent/builder/recall', route => route.fulfill({ json: { success: true,
    recallId: 'synthetic-recall', expiresAt: Date.now() + 300_000,
    memories: [{ blobId: 'synthetic-facts', tier: 'facts', text: 'Synthetic reviewed context. No Mainnet request occurred.' }] } }))
  await page.route('**/api/agent/builder/reviews/checkpoint', route => {
    checkpoint = { id: 'synthetic-checkpoint', digest: 'a'.repeat(64), workspaceId, kind: 'memory', source: 'manual',
      expiresAt: Date.now() + 300_000, text: 'Synthetic checkpoint review only; never approved or written.', project: 'Synthetic fixture', tier: 'facts' }
    return route.fulfill({ json: { approval: checkpoint } })
  })
  await page.route('**/api/agent/builder/approvals', () => { throw new Error('Synthetic memory approvals must never execute.') })
  await page.reload()
  await view(page, 'Memory')
  await page.getByRole('textbox', { name: 'Memory query', exact: true }).fill('Synthetic preferences')
  await page.getByRole('button', { name: 'Recall and review', exact: true }).click()
  const attach = page.getByRole('checkbox', { name: 'Attach reviewed memory 1 · facts', exact: true })
  await attach.check()
  await page.getByRole('button', { name: 'New checkpoint', exact: true }).click()
  await page.getByRole('textbox', { name: 'Reviewed decisions / outcome', exact: true }).fill('Synthetic reviewed checkpoint.')
  await page.getByRole('button', { name: 'Review checkpoint text', exact: true }).click()
  const review = page.getByRole('dialog', { name: 'Review Walrus checkpoint', exact: true })
  await expect(review).toBeVisible()
  await review.getByRole('button', { name: 'Close dialog', exact: true }).click()
  const settings = await openSettings(page, 'Walrus Memory')
  await settings.getByRole('button', { name: 'Reconnect Walrus', exact: true }).click()
  await settings.getByRole('textbox', { name: 'Walrus Memory account object ID', exact: true }).fill(SYNTHETIC_ACCOUNT_ID)
  await settings.getByLabel('Delegate private key', { exact: true }).fill('1'.repeat(64))
  await settings.getByRole('button', { name: 'Verify & connect Walrus', exact: true }).click()
  await expect(settings).toContainText(`Account: ${SYNTHETIC_ACCOUNT_ID}`)
  await expect(settings.getByRole('button', { name: 'Reconnect Walrus', exact: true })).toBeEnabled()
  await settings.getByRole('button', { name: 'Done', exact: true }).click()
  expect(fixture.state.memoryEpoch).toBe(1)
  await expect(attach).toHaveCount(0)
  await expect(review).toBeHidden()
  await expect(page.getByRole('region', { name: 'Pending local approvals', exact: true })).toHaveCount(0)
  expect(fixture.mutations().map(request => request.path)).toEqual(['/models/local', '/connections/memwal'])
  await coding(page, 'A new offline task has no previous wallet-memory attachment.')
  await expect(page.getByRole('button', { name: 'Stop local task', exact: true })).toBeHidden({ timeout: 30_000 })
  expect(requests).toHaveLength(1)
  expect(requests.at(-1)).not.toHaveProperty('memoryIds')
  expect(requests.at(-1)).not.toHaveProperty('recallId')
  expect(fixture.mutations().map(request => request.path)).toEqual(['/models/local', '/connections/memwal', '/builder/prompt'])
  expect(JSON.stringify(await cachedValues(page))).not.toContain('Synthetic reviewed context')
  checkErrors()
})

async function saveCheckpoint(page, text) {
  await view(page, 'Memory')
  const expand = page.getByRole('button', { name: 'New checkpoint', exact: true })
  if (await expand.isVisible()) await expand.click()
  await page.getByRole('textbox', { name: 'Reviewed preferences', exact: true }).fill(text)
  await page.getByRole('button', { name: 'Review checkpoint text', exact: true }).click()
  const review = page.getByRole('dialog', { name: 'Review Walrus checkpoint', exact: true })
  await review.getByRole('checkbox', { name: 'I reviewed this checkpoint and consent to saving this exact text.', exact: true }).check()
  await review.getByRole('button', { name: 'Save reviewed checkpoint', exact: true }).click()
  await expect(review).toBeHidden()
  await expect(page.getByRole('region', { name: 'Local builder workspace', exact: true })).toContainText('Checkpoint write confirmed · mock-')
}
