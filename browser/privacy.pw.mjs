const turnOptions = page => page.locator('details').filter({ has: page.locator('summary').filter({ hasText: 'Turn options' }) })
const authSession = page => page.evaluate(async () => (await fetch('/api/agent/auth/session')).json())
const memoryInventory = page => page.evaluate(async () => {
  const auth = await (await fetch('/api/agent/auth/session')).json()
  return (await (await fetch('/api/agent/memory', { headers: { 'X-RecallLoop-Session': auth.sessionTag } })).json()).inventory
})

test('automatic facts start on, exclude raw chat, deduplicate across conversations, and respect a login-scoped disable choice', async ({ page }) => {
  const checkErrors = failOnPageErrors(page), requests = []
  page.on('request', request => { if (new URL(request.url()).pathname === '/api/agent/chat') requests.push(request.postDataJSON()) })
  await demo(page)
  const options = turnOptions(page)
  await options.locator('summary').click()
  const facts = page.getByRole('checkbox', { name: 'Auto-memory', exact: true })
  const raw = options.getByRole('checkbox', { name: 'Also save raw chat', exact: true })
  await expect(facts).toBeChecked()
  await expect(raw).not.toBeChecked()
  await expect(raw).toBeEnabled()
  await expect(options).toContainText('The relayer processes plaintext')
  await options.locator('summary').click()
  await expect(await send(page, 'I prefer TypeScript and npm: APPROVED_FACTS_ONLY.')).toContainText('facts confirmed')
  expect(requests.at(-1)).toMatchObject({ capture: true, captureMode: 'facts' })
  expect((await memoryInventory(page)).namespaces.find(entry => entry.name.endsWith(':raw')).count).toBe(0)
  const confirmed = (await memoryInventory(page)).total
  await page.locator('header').first().getByRole('button', { name: 'New session', exact: true }).click()
  await expect(await send(page, 'I prefer TypeScript and npm: APPROVED_FACTS_ONLY.')).toContainText('already remembered')
  expect((await memoryInventory(page)).total).toBe(confirmed)
  await setCapture(page, { facts: false })
  await expect(await send(page, 'I prefer TypeScript: CAPTURE_OFF_PRIVATE_CHAT.')).toContainText('Auto-memory is off for this turn')
  expect((await memoryInventory(page)).total).toBe(confirmed)
  await page.reload()
  await expect(facts).not.toBeChecked()
  await setCapture(page, { raw: true })
  await expect(await send(page, 'I prefer small changes: SEPARATE_RAW_CHAT_CONSENT.')).toContainText('transcript records')
  expect(requests.at(-1)).toMatchObject({ capture: true, captureMode: 'both' })
  expect((await memoryInventory(page)).namespaces.find(entry => entry.name.endsWith(':raw')).count).toBeGreaterThanOrEqual(2)
  await setCapture(page, { facts: false })
  await options.locator('summary').click()
  await expect(raw).not.toBeChecked()
  await expect(raw).toBeDisabled()
  await options.locator('summary').click()
  await setCapture(page)
  await send(page, 'I prefer concise TypeScript explanations.')
  expect(requests.at(-1)).toMatchObject({ capture: true, captureMode: 'facts' })
  await leaveSession(page)
  await demo(page)
  await turnOptions(page).locator('summary').click()
  await expect(facts).toBeChecked()
  await expect(raw).not.toBeChecked()
  await expect(raw).toBeEnabled()
  expect((await memoryInventory(page)).total).toBe(0)
  checkErrors()
})

test('logout deletes login-tagged tab caches before late autosave and exit callbacks can repopulate them', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await holdCacheTimers(page)
  await demo(page)
  const auth = await authSession(page), scope = workspaceCacheScope(auth.agentId, auth.sessionTag)
  await openPanel(page)
  await page.getByRole('textbox', { name: 'Edit src/greet.ts', exact: true }).fill('// PRIVATE_LOGIN_PROJECT\n')
  await send(page, 'PRIVATE_LOGIN_CHAT must not survive logout.')
  await page.evaluate(() => window.dispatchEvent(new Event('pagehide')))
  const before = await cachedValues(page)
  expect(before.map(([key]) => key)).toContain(`sessionStorage:${scopedCacheKey(PROJECT_KEY, scope)}`)
  expect(before.map(([key]) => key)).toContain(`sessionStorage:${scopedCacheKey(SESSION_KEY, scope)}`)
  expect(JSON.stringify(before)).toContain('PRIVATE_LOGIN_PROJECT')
  expect(JSON.stringify(before)).toContain('PRIVATE_LOGIN_CHAT')
  expect(JSON.stringify(await cachedValues(page, 'localStorage'))).not.toMatch(/PRIVATE_LOGIN|recallloop\.(sessions|project)/)
  await leaveSession(page)
  await page.evaluate(() => {
    window.recallloopFireDeferredCacheCallbacks()
    window.dispatchEvent(new Event('pagehide'))
    document.dispatchEvent(new Event('visibilitychange'))
  })
  expect(await cachedValues(page, 'sessionStorage')).toEqual([])
  await demo(page)
  const next = await authSession(page)
  expect(next.sessionTag).not.toBe(auth.sessionTag)
  await openPanel(page)
  await expect(page.getByRole('textbox', { name: 'Edit src/greet.ts', exact: true })).not.toHaveValue('// PRIVATE_LOGIN_PROJECT\n')
  await expect(page.locator('article')).toHaveCount(0)
  expect(JSON.stringify(await cachedValues(page))).not.toContain('PRIVATE_LOGIN')
  checkErrors()
})

test('reload without a valid login prunes stale tab history and files instead of restoring them', async ({ page, context }) => {
  const checkErrors = failOnPageErrors(page)
  await demo(page)
  await openPanel(page)
  await page.getByRole('textbox', { name: 'Edit src/greet.ts', exact: true }).fill('// EXPIRED_LOGIN_PROJECT\n')
  await send(page, 'EXPIRED_LOGIN_CHAT cannot be loaded without authentication.')
  await page.evaluate(() => window.dispatchEvent(new Event('pagehide')))
  expect(JSON.stringify(await cachedValues(page))).toContain('EXPIRED_LOGIN')
  // Removing the login cookie reproduces an expired/absent login on reload.
  // Server-side TTL disposal is covered separately by wallet-auth tests.
  await context.clearCookies()
  await page.reload()
  await expect(page.getByRole('region', { name: 'Wallet sign-in', exact: true })).toBeVisible()
  expect(await cachedValues(page, 'sessionStorage')).toEqual([])
  await demo(page)
  await expect(page.locator('article')).toHaveCount(0)
  expect(JSON.stringify(await cachedValues(page))).not.toContain('EXPIRED_LOGIN')
  checkErrors()
})

test('a cross-tab auth notification clears old data even when the next session check cannot reach the server', async ({ page, context }) => {
  const checkErrors = failOnPageErrors(page)
  await installWallet(page)
  await signIn(page)
  const old = await authSession(page)
  await openPanel(page)
  await page.getByRole('textbox', { name: 'Edit src/greet.ts', exact: true }).fill('// OLD_WALLET_NETWORK_FAILURE\n')
  await page.getByRole('textbox', { name: 'Message RecallLoop' }).fill('OLD_WALLET_UNSENT_DRAFT')
  await page.evaluate(() => {
    window.dispatchEvent(new Event('pagehide'))
    window.addEventListener('focus', event => event.stopImmediatePropagation(), true)
  })
  expect(JSON.stringify(await cachedValues(page))).toContain('OLD_WALLET_NETWORK_FAILURE')
  const pair = Ed25519Keypair.generate(), other = await context.newPage()
  await installWallet(other, [pair])
  await other.goto('/#/agent')
  await expect(other.getByRole('button', { name: 'Wallet session details', exact: true })).toBeVisible()
  await page.route('**/api/agent/auth/session', route => route.abort('failed'))
  await leaveSession(other)
  await signIn(other)
  const gate = page.getByRole('region', { name: 'Wallet sign-in', exact: true })
  await expect(gate).toBeVisible()
  await expect(gate.getByRole('alert')).toBeVisible()
  expect(JSON.stringify(await cachedValues(page))).not.toContain('OLD_WALLET')
  await page.unroute('**/api/agent/auth/session')
  await gate.getByRole('button', { name: 'Retry session check', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Wallet session details', exact: true })).toBeVisible()
  expect((await authSession(page)).address).toBe(pair.toSuiAddress())
  await expect(page.getByRole('textbox', { name: 'Message RecallLoop' })).toHaveValue('')
  const stale = await page.evaluate(async tag => {
    const response = await fetch('/api/agent/memory', { headers: { 'X-RecallLoop-Session': tag } })
    return { status: response.status, data: await response.json() }
  }, old.sessionTag)
  expect(stale.status).toBe(409)
  expect(stale.data.code).toBe('session_changed')
  checkErrors()
})

