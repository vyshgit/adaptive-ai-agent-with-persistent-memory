test('key-free handoff has loading, error, retry, copy and download states without writes or raw-namespace export', async ({ page, context }, testInfo) => {
  const checkErrors = failOnPageErrors(page)
  await installWallet(page)
  await signIn(page)
  const auth = await authSession(page)
  const fixture = await installConnectionFixture(page, { tatum: true, memory: true })
  await page.reload()
  await openPanel(page, 'memory')
  const setup = page.getByRole('region', { name: 'Cross-tool memory setup', exact: true })
  const prepare = setup.getByRole('button', { name: 'Prepare cross-tool setup', exact: true })
  const hold = fixture.holdNext('/memory/handoff')
  fixture.failNext('/memory/handoff', 'memory_unavailable', 'Synthetic setup metadata unavailable.')
  try {
    await prepare.click()
    await hold.started.promise
    await expect(setup.getByRole('status')).toContainText('Preparing key-free setup notes')
    await expect(prepare).toBeDisabled()
    await expect(setup.getByRole('button', { name: 'Copy account object id', exact: true })).toHaveCount(0)
    hold.release.resolve()
    await expect(setup.getByRole('alert')).toContainText('Synthetic setup metadata unavailable')
    await expect(prepare).toBeEnabled()
    await prepare.click()
    await expect(setup.getByRole('alert')).toHaveCount(0)
    await expect(setup).toContainText(SYNTHETIC_ACCOUNT_ID)
    await expect(setup).toContainText(memoryNamespace(auth.agentId, 'profile'))
    await expect(setup).toContainText(memoryNamespace(auth.agentId, 'facts'))
    for (const [name, url] of [['Claude Code guide', MEMORY_GUIDES.claudeCode], ['Codex guide', MEMORY_GUIDES.codex], ['MCP reference', MEMORY_GUIDES.reference]]) {
      await expect(setup.getByRole('link', { name, exact: true })).toHaveAttribute('href', url)
      await expect(setup.getByRole('link', { name, exact: true })).toHaveAttribute('rel', 'noopener noreferrer')
    }
    await context.grantPermissions(['clipboard-read', 'clipboard-write'])
    await setup.getByRole('button', { name: 'Copy account object id', exact: true }).click()
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(SYNTHETIC_ACCOUNT_ID)
    await setup.getByText('Key-free setup notes', { exact: true }).click()
    const notes = setup.getByRole('textbox', { name: 'Cross-tool setup notes', exact: true })
    await expect(notes).toHaveAttribute('readonly', '')
    const text = await notes.inputValue()
    expect(text).not.toContain(memoryNamespace(auth.agentId, 'raw'))
    expect(text).toContain('NOT an authorization boundary')
    expect(text).toContain('not live cross-tool validation')
    await setup.getByRole('button', { name: 'Copy cross-tool setup notes', exact: true }).click()
    expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(text)
    const file = await downloadedText(page, () => setup.getByRole('button', { name: 'Download setup notes', exact: true }).click())
    expect(file.name).toBe('recallloop-memory-setup.md')
    expect(file.text).toBe(text)
    expect(fixture.mutations()).toEqual([])
    await page.screenshot({ path: testInfo.outputPath('key-free-cross-tool-setup.png') })
    checkErrors()
  } finally { hold.release.resolve() }
})

test('changing accounts or logging out invalidates pending handoff results and removes old setup controls', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await installWallet(page)
  await signIn(page)
  const fixture = await installConnectionFixture(page, { tatum: true, memory: true })
  await page.reload()
  await openPanel(page, 'memory')
  const setup = page.getByRole('region', { name: 'Cross-tool memory setup', exact: true })
  const prepare = setup.getByRole('button', { name: 'Prepare cross-tool setup', exact: true })
  const hold = fixture.holdNext('/memory/handoff')
  const nextAccount = `0x${'0'.repeat(63)}b`
  try {
    await prepare.click()
    await hold.started.promise
    const settings = await openSettings(page, 'Walrus Memory')
    await settings.getByRole('button', { name: 'Reconnect Walrus', exact: true }).click()
    await settings.getByRole('textbox', { name: 'Walrus Memory account object ID', exact: true }).fill(nextAccount)
    await settings.getByLabel('Delegate private key', { exact: true }).fill('1'.repeat(64))
    await settings.getByRole('button', { name: 'Verify & connect Walrus', exact: true }).click()
    await expect(settings).toContainText(`Account: ${nextAccount}`)
    await settings.getByRole('button', { name: 'Done', exact: true }).click()
    await expect(prepare).toBeEnabled()
    hold.release.resolve()
    await expect(setup.getByRole('textbox', { name: 'Cross-tool setup notes', exact: true })).toHaveCount(0)
    await prepare.click()
    await expect(setup).toContainText(nextAccount)
    await expect(setup).not.toContainText(SYNTHETIC_ACCOUNT_ID)
    const logoutHold = fixture.holdNext('/memory/handoff')
    try {
      await prepare.click()
      await logoutHold.started.promise
      await leaveSession(page)
      logoutHold.release.resolve()
      await expect(page.getByRole('region', { name: 'Cross-tool memory setup', exact: true })).toHaveCount(0)
      expect(JSON.stringify(await cachedValues(page))).not.toContain('RecallLoop cross-tool memory setup')
      expect(JSON.stringify(await cachedValues(page))).not.toContain('1'.repeat(64))
      checkErrors()
    } finally { logoutHold.release.resolve() }
  } finally { hold.release.resolve() }
})

test('legacy cache cleanup requires confirmation, never imports old user data, and leaves tab work and unrelated settings intact', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await page.goto('/#/agent')
  const legacyKeys = ['recallloop.sessions.v1', SESSION_KEY, `${SESSION_KEY}:old-wallet`, `${PROJECT_KEY}:old-wallet`]
  await page.evaluate(keys => {
    for (const key of keys) localStorage.setItem(key, 'OLD_USER_PRIVATE_LEGACY_DATA')
    localStorage.setItem('recallloop.theme', 'dark')
    localStorage.setItem('another-app.settings', 'UNRELATED_SETTING')
  }, legacyKeys)
  await demo(page)
  await expect(page.locator('article')).toHaveCount(0)
  await openPanel(page)
  const editor = page.getByRole('textbox', { name: 'Edit src/greet.ts', exact: true })
  await expect(editor).not.toHaveValue('OLD_USER_PRIVATE_LEGACY_DATA')
  await editor.fill('// KEEP_CURRENT_TAB_PROJECT\n')
  await page.evaluate(() => window.dispatchEvent(new Event('pagehide')))
  const settings = await openSettings(page, 'Advanced')
  const legacy = settings.getByRole('region', { name: 'Legacy browser cache privacy', exact: true })
  await expect(legacy).toContainText('4 old chat/project cache entries remain')
  await expect(legacy).not.toContainText('OLD_USER_PRIVATE_LEGACY_DATA')
  await legacy.getByRole('button', { name: 'Clear legacy browser caches', exact: true }).click()
  const confirm = page.getByRole('dialog', { name: 'Clear old persistent browser caches?', exact: true })
  await expect(confirm).toContainText('all wallets in this browser profile')
  await confirm.getByRole('button', { name: 'Keep old caches', exact: true }).click()
  expect(JSON.stringify(await cachedValues(page, 'localStorage'))).toContain('OLD_USER_PRIVATE_LEGACY_DATA')
  await legacy.getByRole('button', { name: 'Clear legacy browser caches', exact: true }).click()
  await confirm.getByRole('button', { name: 'Clear old caches', exact: true }).click()
  await expect(legacy.getByRole('status')).toContainText('4 old cache entries removed')
  const persistent = await cachedValues(page, 'localStorage')
  expect(persistent).toEqual(expect.arrayContaining([['localStorage:recallloop.theme', 'dark'], ['localStorage:another-app.settings', 'UNRELATED_SETTING']]))
  expect(JSON.stringify(persistent)).not.toContain('OLD_USER_PRIVATE_LEGACY_DATA')
  expect(JSON.stringify(await cachedValues(page, 'sessionStorage'))).toContain('KEEP_CURRENT_TAB_PROJECT')
  await settings.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(editor).toHaveValue('// KEEP_CURRENT_TAB_PROJECT\n')
  checkErrors()
})
