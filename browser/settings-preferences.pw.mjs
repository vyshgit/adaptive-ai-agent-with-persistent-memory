import { test, expect } from './harness.mjs'
import { installWallet, signIn, openSettings, chooseProviderModel, cachedValues, failOnPageErrors, addProjectFile } from './helpers.mjs'
import { installConnectionFixture, SYNTHETIC_ACCOUNT_ID, syntheticConnection } from './fixtures.mjs'
import { PREFERENCES_KEY } from '../src/agent/workspacePreferences.ts'

test.use({ signInBudget: 1 })
const section = (settings, name) => settings.getByRole('tab', { name, exact: true }).click()
const remembered = values => values.filter(([key]) => key.startsWith(`sessionStorage:${PREFERENCES_KEY}:`))
async function setup(page) {
  await installWallet(page); await signIn(page)
  const fixture = await installConnectionFixture(page)
  return { fixture, settings: await openSettings(page) }
}

test('setup variables survive closing Settings and reload, but keys and catalogue eligibility do not', async ({ page }, testInfo) => {
  const checkErrors = failOnPageErrors(page)
  const { fixture, settings } = await setup(page)
  const keys = ['SYNTHETIC_PREFERENCE_MODEL_KEY', 'SYNTHETIC_PREFERENCE_TATUM_KEY', '4'.repeat(64)]
  await settings.getByLabel('Provider', { exact: true }).selectOption('openrouter')
  await settings.getByLabel('Model API key', { exact: true }).fill(keys[0])
  await chooseProviderModel(settings, 'synthetic-discovered-only')
  await section(settings, 'Tatum')
  await settings.getByLabel('Tatum API key', { exact: true }).fill(keys[1])
  await section(settings, 'Walrus Memory')
  await settings.getByLabel('Walrus Memory account object ID', { exact: true }).fill(SYNTHETIC_ACCOUNT_ID)
  await settings.getByLabel('Delegate private key', { exact: true }).fill(keys[2])
  await settings.getByRole('button', { name: 'Done', exact: true }).click()
  const fresh = await openSettings(page)
  await expect(fresh.getByLabel('Provider', { exact: true })).toHaveValue('openrouter')
  await expect(fresh.getByLabel('Model API key', { exact: true })).toHaveValue('')
  await expect(fresh.getByRole('combobox', { name: 'Model', exact: true })).toHaveValue('')
  await expect(fresh.getByRole('button', { name: 'Connect & verify model', exact: true })).toBeDisabled()
  await expect(fresh).toContainText('Remembered: synthetic-discovered-only')
  await section(fresh, 'Walrus Memory')
  await expect(fresh.getByLabel('Walrus Memory account object ID', { exact: true })).toHaveValue(SYNTHETIC_ACCOUNT_ID)
  await expect(fresh.getByLabel('Delegate private key', { exact: true })).toHaveValue('')
  await section(fresh, 'Tatum')
  await expect(fresh.getByLabel('Tatum API key', { exact: true })).toHaveValue('')
  await fresh.getByRole('button', { name: 'Done', exact: true }).click()
  await page.reload()
  const restored = await openSettings(page)
  await expect(restored.getByLabel('Provider', { exact: true })).toHaveValue('openrouter')
  await expect(restored.getByLabel('Model API key', { exact: true })).toHaveValue('')
  await expect(restored.getByRole('combobox', { name: 'Model', exact: true })).toBeDisabled()
  await expect(restored).toContainText('Remembered: synthetic-discovered-only')
  await page.screenshot({ path: testInfo.outputPath('minimal-settings-desktop-dark.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(restored.getByRole('button', { name: 'Done', exact: true })).toBeInViewport()
  expect(await restored.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('minimal-settings-mobile-dark.png'), animations: 'disabled' })
  await restored.getByLabel('Model API key', { exact: true }).fill('SYNTHETIC_FRESH_DISCOVERY_KEY')
  await restored.getByRole('button', { name: 'Load models', exact: true }).click()
  await expect(restored.getByRole('combobox', { name: 'Model', exact: true })).toHaveValue('synthetic-discovered-only')
  await expect(restored.getByRole('button', { name: 'Connect & verify model', exact: true })).toBeEnabled()
  expect(fixture.mutations()).toEqual([])
  const cached = await cachedValues(page)
  expect(remembered(cached)).toHaveLength(1)
  for (const key of [...keys, 'SYNTHETIC_FRESH_DISCOVERY_KEY']) expect(JSON.stringify(cached)).not.toContain(key)
  checkErrors()
})

test('each provider remembers its own base and protocol without carrying a key or old catalogue across providers', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  const { fixture, settings } = await setup(page)
  await settings.getByLabel('Provider', { exact: true }).selectOption('custom')
  await settings.getByLabel('API base URL', { exact: true }).fill('https://api.deepseek.com/v1')
  await settings.getByLabel('API protocol', { exact: true }).selectOption('responses')
  await settings.getByLabel('Model API key', { exact: true }).fill('SYNTHETIC_CUSTOM_PREF_KEY')
  await chooseProviderModel(settings, 'synthetic-model')
  await settings.getByLabel('Provider', { exact: true }).selectOption('openrouter')
  await expect(settings.getByLabel('Model API key', { exact: true })).toHaveValue('')
  await settings.getByLabel('Provider', { exact: true }).selectOption('custom')
  await expect(settings.getByLabel('API base URL', { exact: true })).toHaveValue('https://api.deepseek.com/v1')
  await expect(settings.getByLabel('API protocol', { exact: true })).toHaveValue('responses')
  await expect(settings.getByLabel('Model API key', { exact: true })).toHaveValue('')
  await expect(settings.getByRole('combobox', { name: 'Model', exact: true })).toBeDisabled()
  await expect(settings.getByRole('button', { name: 'Connect & verify model', exact: true })).toBeDisabled()
  await settings.getByRole('button', { name: 'Done', exact: true }).click()
  await page.reload()
  const fresh = await openSettings(page)
  await expect(fresh.getByLabel('Provider', { exact: true })).toHaveValue('custom')
  await expect(fresh.getByLabel('API base URL', { exact: true })).toHaveValue('https://api.deepseek.com/v1')
  await expect(fresh.getByLabel('API protocol', { exact: true })).toHaveValue('responses')
  expect(fixture.mutations()).toEqual([])
  expect(JSON.stringify(await cachedValues(page))).not.toContain('SYNTHETIC_CUSTOM_PREF_KEY')
  checkErrors()
})

test('forgetting remembered fields clears only setup preferences, not open inputs, browser files or active connections', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await installWallet(page); await signIn(page)
  await addProjectFile(page, 'src/greet.ts', '// PRIVATE_PROJECT_NOT_SETUP\n')
  await page.evaluate(() => window.dispatchEvent(new Event('pagehide')))
  const fixture = await installConnectionFixture(page)
  const settings = await openSettings(page)
  await settings.getByLabel('Provider', { exact: true }).selectOption('groq')
  await settings.getByLabel('Model API key', { exact: true }).fill('SYNTHETIC_CLEAR_PREFERENCE_KEY')
  expect(remembered(await cachedValues(page))).toHaveLength(1)
  await section(settings, 'Advanced')
  await settings.getByRole('button', { name: 'Forget remembered fields', exact: true }).click()
  await expect(settings.getByRole('status').filter({ hasText: 'Remembered fields cleared' })).toBeVisible()
  expect(remembered(await cachedValues(page))).toEqual([])
  expect(JSON.stringify(await cachedValues(page))).toContain('PRIVATE_PROJECT_NOT_SETUP')
  await section(settings, 'Model')
  await expect(settings.getByLabel('Provider', { exact: true })).toHaveValue('groq')
  await expect(settings.getByLabel('Model API key', { exact: true })).toHaveValue('SYNTHETIC_CLEAR_PREFERENCE_KEY')
  await settings.getByRole('button', { name: 'Done', exact: true }).click()
  await page.reload()
  const fresh = await openSettings(page)
  await expect(fresh.getByLabel('Provider', { exact: true })).toHaveValue('agentrouter')
  expect(fixture.mutations()).toEqual([])
  checkErrors()
})

test('reload without a valid login prunes setup preferences rather than exposing another login’s fields', async ({ page, context }) => {
  const checkErrors = failOnPageErrors(page)
  const { settings } = await setup(page)
  await settings.getByLabel('Provider', { exact: true }).selectOption('groq')
  expect(remembered(await cachedValues(page))).toHaveLength(1)
  await context.clearCookies()
  await page.reload()
  await expect(page.getByRole('region', { name: 'Wallet sign-in', exact: true })).toBeVisible()
  expect(remembered(await cachedValues(page))).toEqual([])
  checkErrors()
})

test('blocked preference storage preserves usable page inputs and reports save/clear failures without caching keys', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await page.addInitScript(prefix => {
    const set = Storage.prototype.setItem, remove = Storage.prototype.removeItem
    Storage.prototype.setItem = function(key, value) { if (key.startsWith(prefix)) throw new DOMException('Synthetic blocked preferences', 'QuotaExceededError'); return set.call(this, key, value) }
    Storage.prototype.removeItem = function(key) { if (key.startsWith(prefix)) throw new DOMException('Synthetic blocked preference cleanup', 'SecurityError'); return remove.call(this, key) }
  }, `${PREFERENCES_KEY}:`)
  const { fixture, settings } = await setup(page)
  await settings.getByLabel('Provider', { exact: true }).selectOption('groq')
  await settings.getByLabel('Model API key', { exact: true }).fill('SYNTHETIC_BLOCKED_PREFERENCE_KEY')
  await section(settings, 'Advanced')
  await expect(settings.getByRole('status').filter({ hasText: 'Remembered fields could not be saved' })).toBeVisible()
  await settings.getByRole('button', { name: 'Forget remembered fields', exact: true }).click()
  await expect(settings.getByRole('alert')).toContainText('Remembered fields could not be cleared')
  await settings.getByRole('button', { name: 'Done', exact: true }).click()
  const fresh = await openSettings(page)
  await expect(fresh.getByLabel('Provider', { exact: true })).toHaveValue('groq')
  await expect(fresh.getByLabel('Model API key', { exact: true })).toHaveValue('')
  await fresh.getByRole('button', { name: 'Done', exact: true }).click()
  await page.reload()
  const reloaded = await openSettings(page)
  await expect(reloaded.getByLabel('Provider', { exact: true })).toHaveValue('agentrouter')
  expect(remembered(await cachedValues(page))).toEqual([])
  expect(JSON.stringify(await cachedValues(page))).not.toContain('SYNTHETIC_BLOCKED_PREFERENCE_KEY')
  expect(fixture.mutations()).toEqual([])
  checkErrors()
})

test('task model, sidebar, streaming and auto-memory reload while raw transcript consent stays page-only', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await installWallet(page); await signIn(page)
  const fixture = await installConnectionFixture(page, { connection: syntheticConnection() })
  await page.reload()
  await page.getByRole('combobox', { name: 'Model for this turn', exact: true }).selectOption('synthetic-provider|synthetic-discovered-only')
  await page.getByRole('button', { name: 'Collapse session sidebar', exact: true }).click()
  await page.getByRole('group', { name: 'Workspace mode', exact: true }).getByRole('button', { name: 'Plan', exact: true }).click()
  const options = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: 'Turn options' }) })
  await options.locator('summary').click()
  await options.getByRole('checkbox', { name: 'Stream', exact: true }).uncheck()
  await expect(page.getByRole('checkbox', { name: 'Auto-memory', exact: true })).toBeChecked()
  await options.getByRole('checkbox', { name: 'Also save raw chat', exact: true }).check()
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Model for this turn', exact: true })).toHaveValue('synthetic-provider|synthetic-discovered-only')
  await expect(page.getByRole('button', { name: 'Expand session sidebar', exact: true })).toBeVisible()
  await expect(page.getByRole('group', { name: 'Workspace mode', exact: true }).getByRole('button', { name: 'Plan', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await options.locator('summary').click()
  await expect(options.getByRole('checkbox', { name: 'Stream', exact: true })).not.toBeChecked()
  await expect(page.getByRole('checkbox', { name: 'Auto-memory', exact: true })).toBeChecked()
  await expect(options.getByRole('checkbox', { name: 'Also save raw chat', exact: true })).not.toBeChecked()
  await page.getByRole('checkbox', { name: 'Auto-memory', exact: true }).uncheck()
  fixture.setConnections([syntheticConnection({ baseUrl: 'https://api.openai.com/v1' })])
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Model for this turn', exact: true })).toHaveValue('synthetic-provider|synthetic-exact-model')
  await expect(page.getByRole('checkbox', { name: 'Auto-memory', exact: true })).not.toBeChecked()
  expect(fixture.mutations()).toEqual([])
  checkErrors()
})
