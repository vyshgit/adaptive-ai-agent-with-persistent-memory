const withinViewport = async (locator, width, height) => {
  const box = await locator.boundingBox()
  expect(box).not.toBeNull()
  // Flex sizing and scroll offsets can land on half CSS pixels in Chromium.
  expect(box.x).toBeGreaterThanOrEqual(-1)
  expect(box.y).toBeGreaterThanOrEqual(-1)
  expect(box.x + box.width).toBeLessThanOrEqual(width + 1)
  expect(box.y + box.height).toBeLessThanOrEqual(height + 1)
}

test('conversation-first panels and session collapse preserve drafts, edits and approval controls', async ({ page }, testInfo) => {
  const checkErrors = failOnPageErrors(page)
  await demo(page)
  const sidebar = page.getByRole('complementary', { name: 'Sessions sidebar', exact: true })
  const panels = page.getByRole('complementary', { name: 'Project and memory panels', exact: true })
  await expect(sidebar).toBeVisible()
  await expect(panels).toBeHidden()
  const conversation = page.getByRole('region', { name: 'Agent conversation', exact: true })
  expect((await conversation.boundingBox()).width).toBeGreaterThan(1000)
  await page.screenshot({ path: testInfo.outputPath('conversation-first-dark.png') })
  await page.getByRole('button', { name: 'Collapse session sidebar', exact: true }).click()
  await expect(sidebar).toBeHidden()
  await expect(page.getByRole('button', { name: 'Expand session sidebar', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await newSession(page)
  const draft = page.getByRole('textbox', { name: 'Message RecallLoop', exact: true })
  await draft.fill('A draft survives panel collapse.')
  await openPanel(page)
  const editor = page.getByRole('textbox', { name: 'Edit src/greet.ts', exact: true })
  await editor.fill('// A browser edit survives panel collapse.\n')
  await page.getByRole('button', { name: 'Close workspace panel', exact: true }).click()
  await expect(panels).toBeHidden()
  await expect(draft).toHaveValue('A draft survives panel collapse.')
  await openPanel(page)
  await expect(editor).toHaveValue('// A browser edit survives panel collapse.\n')
  const files = panels.getByRole('tab', { name: 'Files', exact: true })
  await files.focus()
  await page.keyboard.press('ArrowRight')
  await expect(panels.getByRole('tab', { name: 'Review', exact: true })).toBeFocused()
  await expect(panels.getByRole('heading', { name: 'No changes to review', exact: true })).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(panels.getByRole('tab', { name: 'Memory', exact: true })).toBeFocused()
  await expect(panels.getByRole('heading', { name: 'Portable memory', exact: true })).toBeVisible()
  await page.keyboard.press('Home')
  await expect(files).toBeFocused()
  await expect(editor).toHaveValue('// A browser edit survives panel collapse.\n')
  await page.getByRole('button', { name: 'Expand session sidebar', exact: true }).click()
  await expect(sidebar).toBeVisible()
  checkErrors()
})

test('settings support arrow-key tabs, a focus trap, Escape and focus restoration', async ({ page }) => {
  const checkErrors = failOnPageErrors(page)
  await installWallet(page)
  await signIn(page)
  const settingsButton = page.getByRole('button', { name: 'Workspace settings', exact: true })
  const settings = await openSettings(page)
  const tabs = settings.getByRole('tablist', { name: 'Settings sections', exact: true })
  await tabs.getByRole('tab', { name: 'Model', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(tabs.getByRole('tab', { name: 'Tatum', exact: true })).toBeFocused()
  await expect(settings.getByRole('tabpanel', { name: 'Tatum', exact: true })).toBeVisible()
  await page.keyboard.press('End')
  await expect(tabs.getByRole('tab', { name: 'Advanced', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(tabs.getByRole('tab', { name: 'Model', exact: true })).toBeFocused()
  const focusStyle = await tabs.getByRole('tab', { name: 'Model', exact: true }).evaluate(node => getComputedStyle(node).boxShadow)
  expect(focusStyle).not.toBe('none')
  await settings.getByRole('button', { name: 'Done', exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(settings.getByRole('button', { name: 'Close dialog', exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(settings.getByRole('button', { name: 'Done', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(settings).toBeHidden()
  await expect(settingsButton).toBeFocused()
  checkErrors()
})

test('stored light preference overrides system dark and reduced motion disables workspace animation', async ({ page }, testInfo) => {
  const checkErrors = failOnPageErrors(page)
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' })
  await page.addInitScript(() => {
    if (!localStorage.getItem('recallloop.theme')) localStorage.setItem('recallloop.theme', 'light')
    window.recallloopObservedThemes = []
    new MutationObserver(() => {
      const theme = document.documentElement?.dataset.theme
      if (theme) window.recallloopObservedThemes.push(theme)
    }).observe(document, { attributes: true, attributeFilter: ['data-theme'], subtree: true })
  })
  await demo(page)
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  expect(await page.evaluate(() => window.recallloopObservedThemes)).not.toContain('dark')
  expect(await page.locator('.workspace-enter').first().evaluate(node => getComputedStyle(node).animationName)).toBe('none')
  expect(await page.locator('.workspace-control').first().evaluate(node => getComputedStyle(node).transitionDuration)).toBe('0s')
  const settings = await openSettings(page)
  expect(await settings.evaluate(node => getComputedStyle(node).animationName)).toBe('none')
  expect(await settings.evaluate(node => getComputedStyle(node, '::backdrop').animationName)).toBe('none')
  expect(await page.locator('.workspace-composer-surface').evaluate(node => getComputedStyle(node).transitionDuration)).toBe('0s')
  await page.screenshot({ path: testInfo.outputPath('settings-stored-light-reduced-motion.png') })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Switch to dark theme', exact: true }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  checkErrors()
})

test('premium motion and dialog blur stay on the right surfaces and fully respect reduced motion', async ({ page }, testInfo) => {
  const checkErrors = failOnPageErrors(page)
  await demo(page)
  const settings = await openSettings(page)
  const styles = await settings.evaluate(node => ({
    animation: getComputedStyle(node).animationName,
    blur: getComputedStyle(node, '::backdrop').backdropFilter,
    scrim: getComputedStyle(node, '::backdrop').backgroundColor,
    background: getComputedStyle(node).backgroundColor,
  }))
  expect(styles.animation).toBe('workspace-dialog-arrive')
  expect(styles.blur).toMatch(/^blur\(/)
  expect(styles.scrim).not.toBe('rgba(0, 0, 0, 0)')
  expect(styles.background).not.toContain('rgba(')
  expect(await page.locator('.workspace-composer-surface').evaluate(node => getComputedStyle(node).backdropFilter)).toBe('none')
  await page.screenshot({ path: testInfo.outputPath('premium-dialog-backdrop-dark.png') })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  expect(await settings.evaluate(node => getComputedStyle(node).animationName)).toBe('none')
  expect(await settings.evaluate(node => getComputedStyle(node, '::backdrop').animationName)).toBe('none')
  await page.keyboard.press('Escape')
  const panel = await openPanel(page)
  expect(await panel.evaluate(node => getComputedStyle(node).animationName)).toBe('none')
  expect(await panel.getByRole('tabpanel').evaluate(node => getComputedStyle(node).animationName)).toBe('none')
  await panel.getByRole('button', { name: 'Close workspace panel', exact: true }).click()
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const opened = await openPanel(page)
  expect(await opened.evaluate(node => getComputedStyle(node).animationName)).toBe('workspace-panel-arrive')
  checkErrors()
})

test('onboarding, short-height composer, panels and connection dialogs remain reachable from mobile through desktop', async ({ page }, testInfo) => {
  const checkErrors = failOnPageErrors(page)
  await installWallet(page)
  await page.goto('/#/agent')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ path: testInfo.outputPath('wallet-onboarding-desktop-dark.png'), fullPage: true })
  await page.setViewportSize({ width: 320, height: 480 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.getByRole('button', { name: 'Connect Wallet', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('wallet-onboarding-mobile-dark.png'), fullPage: true })
  await page.getByRole('button', { name: 'Connect Wallet', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Wallet session details', exact: true })).toBeVisible()
  await addProjectFile(page) // wallet workspaces start blank; seed the editor checked below
  await page.getByRole('button', { name: 'Close workspace panel', exact: true }).click()
  for (const { width, height } of [{ width: 320, height: 480 }, { width: 390, height: 600 }, { width: 768, height: 500 }, { width: 1024, height: 600 }, { width: 1440, height: 800 }]) {
    await page.setViewportSize({ width, height })
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    const draft = page.getByRole('textbox', { name: 'Message RecallLoop', exact: true })
    await draft.fill('Short viewport draft, never submitted.')
    await draft.scrollIntoViewIfNeeded()
    await withinViewport(draft, width, height)
    const send = page.getByRole('button', { name: 'Send', exact: true })
    await send.scrollIntoViewIfNeeded()
    await withinViewport(send, width, height)
    const composer = page.getByRole('region', { name: 'Agent conversation', exact: true }).locator('form')
    expect(await composer.evaluate(node => getComputedStyle(node).overflowY)).toBe('auto')
    if (width === 320) {
      await composer.getByText('Turn options', { exact: false }).click()
      await composer.getByRole('checkbox', { name: 'Stream', exact: true }).scrollIntoViewIfNeeded()
      await withinViewport(composer.getByRole('checkbox', { name: 'Stream', exact: true }), width, height)
      await composer.hover()
      await page.mouse.wheel(0, 1000)
      await expect.poll(() => composer.evaluate(node => node.scrollTop)).toBeGreaterThan(0)
      await page.screenshot({ path: testInfo.outputPath('short-height-composer-mobile-dark.png') })
      await composer.getByText('Turn options', { exact: false }).click()
    }
    expect(await page.locator('#root > div').evaluate(node => node.scrollTop)).toBe(0)
    const settings = await openSettings(page)
    await withinViewport(settings, width, height)
    await withinViewport(settings.getByRole('button', { name: 'Done', exact: true }), width, height)
    expect(await settings.evaluate(node => node.scrollWidth > node.clientWidth)).toBe(false)
    await settings.getByRole('tab', { name: 'Walrus Memory', exact: true }).click()
    await settings.getByLabel('Delegate private key', { exact: true }).scrollIntoViewIfNeeded()
    await withinViewport(settings.getByLabel('Delegate private key', { exact: true }), width, height)
    await page.keyboard.press('Escape')
    const panels = await openPanel(page)
    await page.getByRole('textbox', { name: 'Edit src/greet.ts', exact: true }).scrollIntoViewIfNeeded()
    await withinViewport(page.getByRole('textbox', { name: 'Edit src/greet.ts', exact: true }), width, height)
    const editorBox = await page.getByRole('textbox', { name: 'Edit src/greet.ts', exact: true }).boundingBox()
    const footerBox = await panels.locator('footer').boundingBox()
    expect(editorBox.y + editorBox.height).toBeLessThanOrEqual(footerBox.y + 1)
    if (width === 320) await page.screenshot({ path: testInfo.outputPath('short-height-files-mobile-dark.png') })
    await panels.getByRole('button', { name: 'Close workspace panel', exact: true }).click()
  }
  await page.screenshot({ path: testInfo.outputPath('workspace-responsive-desktop-dark.png') })
  checkErrors()
})
